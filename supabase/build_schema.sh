#!/usr/bin/env bash
# Builds schema.sql, the single paste-into-the-SQL-Editor file, from the
# versioned migrations in migrations/. Every migration is written to be safe to
# re-run, so pasting the whole file on a project that already has some of them
# is fine. Run this after adding or changing a migration, then commit both.
#   Usage: supabase/build_schema.sh          (writes supabase/schema.sql)
#          supabase/build_schema.sh --check  (exits 1 if schema.sql is out of date)
set -euo pipefail
cd "$(dirname "$0")"
out=$(mktemp)
{
  echo "-- Mr. Todo database schema — GENERATED by build_schema.sh from migrations/*.sql."
  echo "-- Edit the files in migrations/, not this one. Safe to run more than once."
  echo "-- Migrations included, in order:"
  for f in migrations/*.sql; do echo "--   $(basename "$f")"; done
  for f in migrations/*.sql; do
    echo; echo "-- ============================================================================"
    echo "-- migration: $(basename "$f")"
    echo "-- ============================================================================"
    cat "$f"
  done
} > "$out"
if [ "${1:-}" = "--check" ]; then
  cmp -s "$out" schema.sql || { echo "schema.sql is out of date: run supabase/build_schema.sh"; rm "$out"; exit 1; }
  rm "$out"; echo "schema.sql is up to date"
else
  chmod 644 "$out"; mv "$out" schema.sql; echo "wrote schema.sql ($(wc -l < schema.sql) lines from $(ls migrations/*.sql | wc -l) migrations)"
fi
