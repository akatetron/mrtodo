#!/usr/bin/env node
// Registers the photographs in assets/services/ so the app bundles them.
//   1. Put one image per service family in app/assets/services/, named after the
//      family key: everyday-tech.jpg, assistance.jpg, errands.jpg, setup-organise.jpg
//      (also: concierge.jpg for "Not sure where to start?", someone-else.jpg for
//      "Arrange help for someone you care about"). jpg, jpeg, png or webp.
//   2. Run:  node scripts/register-photos.js
// It writes src/assets/servicePhotos.js. A family without a file keeps the built-in artwork.
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'assets', 'services');
const out = path.join(__dirname, '..', 'src', 'assets', 'servicePhotos.js');
const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /^[a-z0-9-]+\.(jpe?g|png|webp)$/i.test(f)).sort() : [];
const lines = files.map((f) => `  '${f.replace(/\.[^.]+$/, '')}': require('../../assets/services/${f}'),`);
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, `// GENERATED by scripts/register-photos.js. Do not edit by hand.
// Photographs bundled in the app, by family key. Empty until photos are added: see docs/PHOTOS.md.
export const servicePhotos = {
${lines.join('\n')}
};
`);
console.log(files.length ? `Registered ${files.length} photo(s): ${files.join(', ')}` : 'No photos found in assets/services/. The built-in artwork will be used.');
